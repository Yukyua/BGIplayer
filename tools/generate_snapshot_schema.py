"""Generate named-field debug snapshot visitors using the local Clang AST.

The generated manifest includes host exclusions so a changed VM layout changes
the snapshot schema identity. Run from the BGIplayer directory.
"""
import ctypes as C, json, hashlib, subprocess
from pathlib import Path
toolchain = Path(subprocess.check_output(['xcrun', '--find', 'clang++'], text=True).strip()).parent.parent
sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
lib=C.CDLL(str(toolchain / 'lib/libclang.dylib'))
class String(C.Structure): _fields_=[('data',C.c_void_p),('flags',C.c_uint)]
class Cursor(C.Structure): _fields_=[('kind',C.c_uint),('xdata',C.c_int),('data',C.c_void_p*3)]
class Type(C.Structure): _fields_=[('kind',C.c_int),('data',C.c_void_p*2)]
def setup(name,result,args):
 f=getattr(lib,name);f.restype=result;f.argtypes=args;return f
create=setup('clang_createIndex',C.c_void_p,[C.c_int,C.c_int])
parse=setup('clang_parseTranslationUnit',C.c_void_p,[C.c_void_p,C.c_char_p,C.POINTER(C.c_char_p),C.c_int,C.c_void_p,C.c_uint,C.c_uint])
root=setup('clang_getTranslationUnitCursor',Cursor,[C.c_void_p])
spell=setup('clang_getCursorSpelling',String,[Cursor]);ts=setup('clang_getTypeSpelling',String,[Type]);typ=setup('clang_getCursorType',Type,[Cursor]);canon=setup('clang_getCanonicalType',Type,[Type]);
getstr=setup('clang_getCString',C.c_char_p,[String]);dispose=setup('clang_disposeString',None,[String])
def string(s):
 r=getstr(s);o=r.decode() if r else '';dispose(s);return o
callback=C.CFUNCTYPE(C.c_uint,Cursor,Cursor,C.c_void_p)
visit=setup('clang_visitChildren',C.c_uint,[Cursor,callback,C.c_void_p])
isdef=setup('clang_isCursorDefinition',C.c_uint,[Cursor])
records={}
def walk(c,prefix=''):
 name=string(spell(c))
 if c.kind==22:
  if name!='bgiplayer' and not prefix:return
  prefix=(prefix+'::' if prefix else '')+name
 elif c.kind in (2,4):
  if not name or not isdef(c):return
  prefix=(prefix+'::' if prefix else '')+name
  fields=[]
  @callback
  def fields_visit(child,parent,data):
   if child.kind==6:fields.append({'name':string(spell(child)),'type':string(ts(typ(child))),'canonical':string(ts(canon(typ(child))))})
   elif child.kind in (2,4):walk(child,prefix)
   return 1
  visit(c,fields_visit,None)
  if fields:records[prefix]=fields
  return
 @callback
 def children(child,parent,data):
  if child.kind in (22,2,4):walk(child,prefix)
  return 1
 visit(c,children,None)
args=['-x','c++','-std=c++20','-Iinclude','-isysroot',sdk,'-isystem',str(toolchain/'usr/include/c++/v1')]
# Xcode and Command Line Tools use different toolchain roots.
if not (toolchain/'usr/include/c++/v1').is_dir():
 args[-1] = str(toolchain/'include/c++/v1')
a=(C.c_char_p*len(args))(*[x.encode() for x in args]);stub=Path('/tmp/bgi_snapshot_schema_input.cpp')
stub.write_text('#include \"bgiplayer/vm.hpp\"\n#include \"bgiplayer/audio_backend.hpp\"\n')
tu=parse(create(0,0),str(stub).encode(),a,len(args),None,0,0x40)
if not tu:raise RuntimeError('parse failed')
num_diags=setup('clang_getNumDiagnostics',C.c_uint,[C.c_void_p])
get_diag=setup('clang_getDiagnostic',C.c_void_p,[C.c_void_p,C.c_uint])
diag_severity=setup('clang_getDiagnosticSeverity',C.c_uint,[C.c_void_p])
diag_spelling=setup('clang_getDiagnosticSpelling',String,[C.c_void_p])
dispose_diag=setup('clang_disposeDiagnostic',None,[C.c_void_p])
errors=[]
for i in range(num_diags(tu)):
 d=get_diag(tu,i)
 if diag_severity(d)>=3: errors.append(string(diag_spelling(d)))
 dispose_diag(d)
if errors: raise RuntimeError('snapshot schema parse errors: '+ '; '.join(errors))
walk(root(tu))
records={k:v for k,v in records.items() if k.startswith('bgiplayer::')}
# These fields are host bindings or non-owning views rebuilt after load.
exclude={
 'bgiplayer::VM::GraphicsSurface': {'defer_rgba_mirror'},
 'bgiplayer::PlainTextLayout': {'ruby_runs'}, # Consumed into glyph nodes before procedure installation.
 'bgiplayer::Memory': {'active_code_', 'code_fallbacks_', 'frame_byte_watches_'},
 'bgiplayer::NativeRegistry': {'handlers_'},
 'bgiplayer::D0Subsystem::Worker': {'critical_section', 'event', 'thread'},
 'bgiplayer::SdlAudioBackend': {'mutex_', 'device_id_', 'initialized_',
    'cached_bgm_encoded_', 'cached_bgm_clip_',
    'cached_bgm_sample_rate_', 'cached_bgm_channels_'},
 'bgiplayer::VM': {'natives_', 'lock_registry_mutex_', 'lock_registry_event_',
                    'display_warning_keys_', 'display_warning_context_', 'display_failure_serial_',
                    'display_frame_gpu_cached_'},
}
for name, fields in records.items():
 for f in fields:
  f['host_binding'] = ('std::function<' in f['canonical'] or
     f['name'] in exclude.get(name,set()) or 'std::span<' in f['canonical'])
manifest=json.dumps(records,sort_keys=True,indent=2)+'\n'
identity=hashlib.sha256(manifest.encode()).hexdigest()
output=['// Generated by tools/generate_snapshot_schema.py; do not edit.',
 f'static constexpr std::string_view schema_identity = "{identity}";']
for name, fields in sorted(records.items()):
 if name in {'bgiplayer::NativeRegistry','bgiplayer::PixelBuffer'}: continue
 output.append(f'template<class A> static void fields(A& a, {name}& v) {{')
 for f in fields:
  if not f['host_binding']: output.append(f'    a(v.{f["name"]});')
 output.append('}')
 output.append(f'static void transfer({name}& dst, {name}& src) {{')
 for f in fields:
  if not f['host_binding']: output.append(f'    move_value(dst.{f["name"]}, src.{f["name"]});')
 output.append('}')
Path('include/bgiplayer/snapshot_schema.inc').write_text('\n'.join(output)+'\n')
Path('docs/SNAPSHOT_SCHEMA.json').write_text(manifest)
print(len(records),'records',sum(map(len,records.values())),'fields',identity)
